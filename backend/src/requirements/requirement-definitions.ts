export const REQUIREMENT_IDS = [
  'ИБ-01', 'ИБ-02', 'ИБ-03', 'ИБ-04', 'ИБ-05', 'ИБ-06', 'ИБ-07', 'ИБ-08',
] as const;

export type RequirementId = (typeof REQUIREMENT_IDS)[number];

/**
 * ТЗ п. 4.5 и 4.4.5.
 *
 * PASS                  — механизм найден, доказательство получено, признаков нарушения нет.
 * VIOLATION             — механизм отсутствует либо реализован некорректно. Отсутствие
 *                         реализации является нарушением в той же мере, что и
 *                         некорректная реализация (п. 4.4.5).
 * INSUFFICIENT_EVIDENCE — данных для вывода недостаточно. НЕ является PASS.
 * NOT_APPLICABLE        — требование неприменимо к этому типу проекта.
 */
export type RequirementStatus =
  | 'PASS'
  | 'VIOLATION'
  | 'INSUFFICIENT_EVIDENCE'
  | 'NOT_APPLICABLE';

export type EvidenceKind = 'SUPPORTS' | 'VIOLATES' | 'CONTEXT';

export interface RequirementEvidence {
  filePath: string;
  line: number;
  snippet: string;
  /** Что именно доказывает эта строка. */
  note: string;
  kind: EvidenceKind;
}

export interface RequirementViolation {
  /** Путь к файлу, номер строки — ТЗ п. 4.6.2. */
  filePath: string | null;
  lineStart: number | null;
  lineEnd: number | null;
  /** Наименование функции, класса или конфигурационного параметра — ТЗ п. 4.6.2. */
  symbol: string | null;
  /** Фрагмент кода или конфигурации, послуживший основанием — ТЗ п. 4.6.2. */
  evidence: string;
  /** В чём именно состоит несоответствие — ТЗ п. 4.6.2. */
  explanation: string;
  severity: 'CRITICAL' | 'HIGH' | 'MEDIUM' | 'LOW';
  confidence: 'HIGH' | 'MEDIUM' | 'LOW';
  recommendation: string;
}

export interface RequirementResult {
  requirementId: RequirementId;
  title: string;
  /** Точная формулировка из ТЗ — попадает в отчёт (п. 4.6.2). */
  requirementText: string;
  status: RequirementStatus;
  confidence: 'HIGH' | 'MEDIUM' | 'LOW';
  /** Краткое обоснование статуса. */
  summary: string;
  evidence: RequirementEvidence[];
  violations: RequirementViolation[];
  /** Почему данных недостаточно — заполняется только для INSUFFICIENT_EVIDENCE. */
  insufficientReason: string | null;
}

export interface RequirementDefinition {
  id: RequirementId;
  /** Пункт ТЗ. */
  clause: string;
  title: string;
  /** Дословная формулировка требования. */
  text: string;
  /**
   * Сквозное требование (ТЗ п. 1.19): соответствие обеспечивается общими
   * компонентами проекта и не может быть установлено по отдельному файлу.
   */
  crossCutting: boolean;
  /** Требование применимо только к проектам с HTTP-поверхностью. */
  requiresWebSurface: boolean;
  /** Нормативная база, к которой требование отнесено (ТЗ п. 3.1). */
  regulatoryBasis: string[];
  /** Severity нарушения этого требования по умолчанию. */
  severity: 'CRITICAL' | 'HIGH' | 'MEDIUM';
}

